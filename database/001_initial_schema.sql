
-- Wildlife Threat Database
-- PostgreSQL Schema

-- This script defines the database schema for the Wildlife Threat Database project, 
-- including tables for users, roles, user addresses, media assets, and officer applications.

-- ====================================
-- USERS
-- ====================================

CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    full_name VARCHAR(150) NOT NULL,
    username VARCHAR(50) UNIQUE NOT NULL,
    email VARCHAR(320) UNIQUE NOT NULL,
    password VARCHAR(128) NOT NULL,
    nic_encrypted TEXT,
    mobile_number VARCHAR(20),
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- ====================================
-- USER ADDRESSES
-- ====================================

CREATE TABLE IF NOT EXISTS user_addresses (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id),
    address_type VARCHAR(20) NOT NULL CHECK (address_type IN ('personal', 'work')),
    address_line_1 VARCHAR(255),
    address_line_2 VARCHAR(255),
    address_line_3 VARCHAR(255),
    city VARCHAR(100),
    province VARCHAR(100),
    postal_code VARCHAR(20),
    country_code CHAR(2) NOT NULL DEFAULT 'LK',

    UNIQUE (user_id, address_type)
);

-- CREATE TABLE IF NOT EXISTS does not add this check to an existing table.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'user_addresses_address_type_check'
          AND conrelid = 'user_addresses'::regclass
    ) THEN
        ALTER TABLE user_addresses
        ADD CONSTRAINT user_addresses_address_type_check
        CHECK (address_type IN ('personal', 'work'));
    END IF;
END
$$;


-- ====================================
-- ROLES
-- ====================================

CREATE TABLE IF NOT EXISTS roles (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) UNIQUE NOT NULL,
    description TEXT
);


-- ====================================
-- USER ROLES
-- ====================================

CREATE TABLE IF NOT EXISTS user_roles (
    user_id UUID NOT NULL REFERENCES users(id),
    role_id INT NOT NULL REFERENCES roles(id),
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY (user_id, role_id)
);


-- ====================================
-- MEDIA ASSETS
-- ====================================

CREATE TABLE IF NOT EXISTS media_assets (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_user_id UUID NOT NULL REFERENCES users(id),
    storage_key VARCHAR(512) UNIQUE NOT NULL,
    original_filename VARCHAR(255),
    mime_type VARCHAR(100),
    file_size BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    uploaded_at TIMESTAMPTZ
);


-- ====================================
-- OFFICER APPLICATIONS
-- ====================================

CREATE TABLE IF NOT EXISTS officer_applications (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id),
    designation VARCHAR(100),
    office_phone VARCHAR(20),
    verification_media_id UUID REFERENCES media_assets(id),
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    reviewed_by UUID REFERENCES users(id),
    reviewed_at TIMESTAMPTZ,
    review_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- ====================================
-- INDEXES
-- ====================================

CREATE INDEX IF NOT EXISTS idx_users_created_at_id
ON users (created_at, id);

CREATE UNIQUE INDEX IF NOT EXISTS users_username_ci_unique ON users (lower(username));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_ci_unique ON users (lower(email));

CREATE INDEX IF NOT EXISTS idx_user_roles_role_id
ON user_roles (role_id);

CREATE INDEX IF NOT EXISTS idx_officer_applications_status_created_at
ON officer_applications (status, created_at);

CREATE INDEX IF NOT EXISTS idx_officer_applications_user_id_status
ON officer_applications (user_id, status);


-- ====================================
-- DEFAULT ROLES
-- ====================================

INSERT INTO roles (code, description)
VALUES
    ('admin', 'Administrator with full access'),
    ('officer', 'Officer with limited access'),
    ('user', 'Regular user with basic access'),
    ('moderator', 'Moderator with content management access')
ON CONFLICT (code) DO NOTHING;
